// ============================================================
//  CuratedBase.cpp
//
//  Krisztiaan's curated map-512 conversion, ported into MapSizeExt.
//  This is the alternative to our broad inline sweep (ApplyStridePatches +
//  broad ApplyBoundsPatches). His approach applies only these exact byte
//  patches, so it AVOIDS the broad-sweep false-positive class that gives us
//  the wall-connect and sidebar-brightness bugs (see docs/BUG-ATLAS.md).
//
//  Three tables, all verified against pinned gamemd SHA 3e81a617...d308600:
//    * kCurated       : the 74 exact map-plane byte patches (owner-core,
//                       pathfinding table, subzone scale, overlay-load,
//                       visibility/shroud, iso-pack, veinhole).
//    * kSubzoneMovzx  : 14 subzone consumers movsx(0f bf)->movzx(0f b7),
//                       the unsigned-subzone fix (full 16-bit namespace).
//    * kModule        : 2 Phobos.dll waypoint patches (RVA-relative).
//
//  Gated by [Debug] CuratedBase in Config. When on, Main.cpp applies these
//  INSTEAD of the broad sweep, and pairs them with the 0xFFFE producer
//  ceiling (see Subzone_SaturateID in Hooks.cpp) plus our crash guards.
//  300x300 support is added on top separately (his base caps ~250x250).
// ============================================================

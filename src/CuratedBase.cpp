// Verify-then-write into (read-only) .text. Returns 1 applied, 0 mismatch/skip.
int writeBytes(DWORD va, const BYTE* exp, const BYTE* rep, BYTE n)
{
    DWORD old = 0;
    if (!VirtualProtect(reinterpret_cast<void*>(va), n, PAGE_EXECUTE_READWRITE, &old))
        return 0;
    int ok = (memcmp(reinterpret_cast<void*>(va), exp, n) == 0);
    if (ok) memcpy(reinterpret_cast<void*>(va), rep, n);
    VirtualProtect(reinterpret_cast<void*>(va), n, old, &old);
    return ok;
}

